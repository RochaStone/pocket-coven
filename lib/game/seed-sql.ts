import { ACHIEVEMENTS, ACTIVITIES, CHARACTERS, GAME_CONFIG, ITEMS, LOCATIONS, SHARED_EVENTS } from "./catalog.ts";

export const FOUNDING_COVEN_ID = "00000000-0000-4000-8000-000000000001";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const b = (v: boolean | undefined) => (v ? "true" : "false");
const arr = (v: string[]) => `array[${v.map(q).join(", ")}]::text[]`;

// Idempotent: safe to re-run against an existing database (content upserts, witches untouched once created).
export function buildSeedSql(): string {
  const lines: string[] = [
    "-- GENERATED by scripts/gen-seed.ts from lib/game/catalog.ts. Do not edit by hand.",
    "begin;",
    "",
    `insert into public.covens (id, slug, name) values (${q(FOUNDING_COVEN_ID)}, 'pocket-coven', 'The Founding Coven') on conflict (id) do nothing;`,
    "",
  ];

  for (const [key, value] of Object.entries({ ...GAME_CONFIG, shared_events: SHARED_EVENTS, day_timezone: "Asia/Makassar" })) {
    lines.push(`insert into public.game_config (key, value) values (${q(key)}, ${j(value)}) on conflict (key) do nothing;`);
  }
  lines.push("");

  for (const l of LOCATIONS) {
    lines.push(`insert into public.locations (id, name, world, blurb) values (${q(l.id)}, ${q(l.name)}, ${q(l.world)}, ${q(l.blurb)}) on conflict (id) do update set name = excluded.name, world = excluded.world, blurb = excluded.blurb;`);
  }
  lines.push("");

  for (const i of ITEMS) {
    lines.push(`insert into public.items (id, name, category, slot, price, placeable, rarity, description) values (${q(i.id)}, ${q(i.name)}, ${q(i.category)}, ${q(i.slot)}, ${n(i.price)}, ${b(i.placeable)}, ${q(i.rarity)}, ${q(i.description)}) on conflict (id) do update set name = excluded.name, category = excluded.category, slot = excluded.slot, price = excluded.price, placeable = excluded.placeable, rarity = excluded.rarity, description = excluded.description;`);
  }
  lines.push("");

  for (const a of ACTIVITIES) {
    const loot = (a.loot ?? []).map((l) => ({ item_id: l.itemId, chance: l.chance }));
    lines.push(`insert into public.activities (id, location_id, name, effects, pearls, xp, cooldown_seconds, adult_only, loot, animation, flavour_count) values (${q(a.id)}, ${q(a.locationId)}, ${q(a.name)}, ${j(a.effects)}, ${a.pearls}, ${a.xp}, ${a.cooldownSeconds}, ${b(a.adultOnly)}, ${j(loot)}, ${q(a.animation)}, ${a.flavour.length}) on conflict (id) do update set location_id = excluded.location_id, name = excluded.name, effects = excluded.effects, pearls = excluded.pearls, xp = excluded.xp, cooldown_seconds = excluded.cooldown_seconds, adult_only = excluded.adult_only, loot = excluded.loot, animation = excluded.animation, flavour_count = excluded.flavour_count;`);
  }
  lines.push("");

  for (const a of ACHIEVEMENTS) {
    lines.push(`insert into public.achievements (id, name, description) values (${q(a.id)}, ${q(a.name)}, ${q(a.description)}) on conflict (id) do update set name = excluded.name, description = excluded.description;`);
  }
  lines.push("");

  for (const c of CHARACTERS) {
    lines.push(`insert into public.characters (id, coven_id, name, title, pronoun_subject, pronoun_object, pronoun_possessive, pronoun_plural, baby_aesthetic, is_owner_character, description, personality, look, default_equipped, starter_items) values (${q(c.id)}, ${q(FOUNDING_COVEN_ID)}, ${q(c.name)}, ${q(c.title)}, ${q(c.pronouns.subject)}, ${q(c.pronouns.object)}, ${q(c.pronouns.possessive)}, ${b(c.pronouns.plural)}, ${b(c.babyAesthetic)}, ${b(c.isOwnerCharacter)}, ${q(c.description)}, ${q(c.personality)}, ${j(c.look)}, ${j(c.equipped)}, ${arr(c.starterItems)}) on conflict (id) do update set default_equipped = excluded.default_equipped, starter_items = excluded.starter_items, baby_aesthetic = excluded.baby_aesthetic, is_owner_character = excluded.is_owner_character;`);
  }
  lines.push("");
  lines.push("-- Initialise each witch once (stats, starter wardrobe, room). Never resets an existing witch.");
  for (const c of CHARACTERS) {
    lines.push(`select game.init_character(${q(c.id)}) where not exists (select 1 from public.character_stats where character_id = ${q(c.id)});`);
  }
  lines.push("", "commit;", "");
  return lines.join("\n");
}
